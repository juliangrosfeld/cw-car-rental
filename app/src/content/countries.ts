/** The picker's order: the priority countries, then everything A to Z. The
 *  priority ones are not repeated further down. */
export const COUNTRIES: readonly string[] = [
  ...PRIORITY_COUNTRIES,
  ...ALPHABETICAL.filter((name) => !PRIORITY_COUNTRIES.includes(name)),
]

const COUNTRY_SET = new Set(COUNTRIES)

export function isCountry(value: unknown): value is string {
  return typeof value === 'string' && COUNTRY_SET.has(value)
}

/** Lowercased with accents removed, so "curacao" finds "Curaçao" and "turkiye"
 *  finds "Türkiye". Used for searching only; the stored value keeps its accents. */
export function foldCountry(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim()
}

/** Countries matching what was typed: names that START with it first, then
 *  names that merely contain it. An empty query returns the full list. */
export function searchCountries(query: string): string[] {
  const q = foldCountry(query)
  if (q === '') return [...COUNTRIES]
  const starts: string[] = []
  const contains: string[] = []
  for (const name of COUNTRIES) {
    const folded = foldCountry(name)
    if (folded.startsWith(q)) starts.push(name)
    else if (folded.includes(q)) contains.push(name)
  }
  return [...starts, ...contains]
}
